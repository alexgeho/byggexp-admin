// Minimal markdown: [label](url) links and line breaks; everything else is
// plain text (React escapes it). Panel paths open in-app, site paths and
// external links open byggexp.se in a new tab.
const PANEL_PATH = /^\/(company|worker|admin|projects)(\/|$)/;

function renderContent(text) {
  const linkRe = /\[([^\]]+)\]\(([^)]+)\)/g;
  const lines = text.replace(/\*\*(.+?)\*\*/g, '$1').replace(/^#{1,6}\s+/gm, '').split('\n');
  return lines.map((line, li) => {
    const parts = [];
    let last = 0;
    let m;
    linkRe.lastIndex = 0;
    while ((m = linkRe.exec(line)) !== null) {
      if (m.index > last) parts.push(line.slice(last, m.index));
      const label = m[1];
      const href = m[2];
      const key = `${li}-${m.index}`;
      if (PANEL_PATH.test(href)) {
        parts.push(<Link key={key} href={href}>{label}</Link>);
      } else if (href.startsWith('/') || /^https?:\/\//.test(href)) {
        const url = href.startsWith('/') ? `${SITE}${href}` : href;
        parts.push(<a key={key} href={url} target="_blank" rel="noopener noreferrer">{label}</a>);
      } else {
        parts.push(label);
      }
      last = m.index + m[0].length;
    }
    if (last < line.length) parts.push(line.slice(last));
    return (
      <Fragment key={li}>
        {parts}
        {li < lines.length - 1 ? <br /> : null}
      </Fragment>
    );
  });
}

export default function SupportChat() {
  const { lang } = useLanguage();
  const copy = COPY[lang] || COPY.en;

  const [open, setOpen] = useState(false);
  const [teaser, setTeaser] = useState(false);
  const [input, setInput] = useState('');
  const [messages, setMessages] = useState([]);
  const [streaming, setStreaming] = useState(false);
  const scrollRef = useRef(null);

  // Proactive offer: after 15 s the chat opens by itself on desktop; on phones
  // a small bubble by the button offers help instead. Once per 24 h per user.
  useEffect(() => {
    let last = 0;
    try {
      last = Number(window.localStorage.getItem(OFFER_KEY) || 0);
    } catch {
      /* storage blocked */
    }
    if (Date.now() - last < 24 * 3600_000) return undefined;
    const timer = window.setTimeout(() => {
      try {
        window.localStorage.setItem(OFFER_KEY, String(Date.now()));
      } catch {
        /* storage blocked */
      }
      if (window.matchMedia('(max-width: 840px)').matches) setTeaser(true);
      else setOpen(true);
    }, 15_000);
    return () => window.clearTimeout(timer);
  }, []);

  useEffect(() => {
    scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: 'smooth' });
  }, [messages, open]);

  async function send() {
    const text = input.trim();
    if (!text || streaming) return;
    const nextMessages = [...messages, { role: 'user', content: text }];
    setMessages([...nextMessages, { role: 'assistant', content: '' }]);
    setInput('');
    setStreaming(true);

    const setLast = (content) => setMessages((prev) => {
      const next = prev.slice();
      next[next.length - 1] = { role: 'assistant', content };
      return next;
    });

    try {
      const res = await fetch(CHAT_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ messages: nextMessages, lang, context: 'admin' }),
      });
      if (!res.ok || !res.body) throw new Error('bad response');
      const reader = res.body.getReader();
      const decoder = new TextDecoder();
      let acc = '';
      while (true) {
        const { done, value } = await reader.read();
        if (done) break;
        acc += decoder.decode(value, { stream: true });
        setLast(acc);
      }
      if (!acc) setLast(copy.error);
    } catch {
      setLast(copy.error);
    } finally {
      setStreaming(false);
    }
  }

  const openChat = () => { setTeaser(false); setOpen(true); };

  return (
    <>
      {!open && teaser ? (
        <div className="support-chat__teaser">
          <button type="button" className="support-chat__teaser-text" onClick={openChat}>
            {copy.teaser}
          </button>
          <button type="button" className="support-chat__teaser-close" aria-label={copy.close} onClick={() => setTeaser(false)}>
            ✕
          </button>
        </div>
      ) : null}

      {!open ? (
        <button type="button" className="support-chat__fab" onClick={openChat} aria-label={copy.open} title={copy.title}>
          <svg width="22" height="22" viewBox="0 0 24 24" fill="none" aria-hidden="true">
            <path d="M21 12a8 8 0 0 1-8 8H7l-3 3v-4a8 8 0 1 1 17-7Z" stroke="currentColor" strokeWidth="2" strokeLinejoin="round" />
          </svg>
        </button>
      ) : null}

      {open ? (
        <div className="support-chat__panel" role="dialog" aria-label={copy.title}>
          <div className="support-chat__header">
            <div>
              <strong>{copy.title}</strong>
              <span className="support-chat__sub">{copy.subtitle}</span>
            </div>
            <button type="button" className="support-chat__close" onClick={() => setOpen(false)} aria-label={copy.close}>
              ✕
            </button>
          </div>

          <div className="support-chat__messages" ref={scrollRef}>
            <div className="support-chat__msg support-chat__msg--assistant">{copy.greeting}</div>
            {messages.map((m, i) => (
              <div key={i} className={`support-chat__msg support-chat__msg--${m.role}`}>
                {m.role === 'assistant'
                  ? (m.content ? renderContent(m.content) : <span className="support-chat__typing">…</span>)
                  : m.content}
              </div>
            ))}
          </div>

          <form className="support-chat__input" onSubmit={(e) => { e.preventDefault(); send(); }}>
            <input
              type="text"
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder={copy.placeholder}
              aria-label={copy.placeholder}
            />
            <button type="submit" disabled={streaming || input.trim() === ''}>
              {copy.send}
            </button>
          </form>
          <p className="support-chat__disclaimer">{copy.disclaimer}</p>
        </div>
      ) : null}
    </>
  );
}
